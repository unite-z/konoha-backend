-- AV-276 (RF-INC-002, CU-021 2a): antes de clasificar, el jefe puede pedir una inspección en campo a
-- un ingeniero o practicante. La incidencia sigue Registrada hasta que se clasifica.

CREATE TABLE mod03_inspeccion_incidencia (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    incidencia_id bigint NOT NULL REFERENCES mod03_incidencia (id),
    responsable_id bigint NOT NULL REFERENCES core_usuario (id),
    que_verificar varchar(300),
    solicitada_por_id bigint NOT NULL REFERENCES core_usuario (id),
    fecha_hora timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX mod03_inspeccion_incidencia_ciclo ON mod03_inspeccion_incidencia (incidencia_id);
