CREATE TABLE mod05_verificacionseguridad (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    atencion_id bigint NOT NULL REFERENCES mod05_atenciontercerizada(id),
    medidas text NOT NULL CHECK (btrim(medidas) <> ''),
    usuario_id bigint NOT NULL REFERENCES mod05_usuario(id),
    fecha_creacion timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX ON mod05_verificacionseguridad(atencion_id, id);
