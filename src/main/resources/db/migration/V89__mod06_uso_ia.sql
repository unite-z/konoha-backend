-- AV-396: una fila por llamada a la IA (también las que fallan), para el panel de uso y costes.
CREATE TABLE mod06_uso_ia (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    solicitado_en timestamptz NOT NULL DEFAULT now(),
    asistente varchar(40) NOT NULL,
    proveedor varchar(60) NOT NULL,
    modelo varchar(80) NOT NULL,
    duracion_ms integer NOT NULL,
    correcto boolean NOT NULL,
    error varchar(300),
    tokens_entrada integer,
    tokens_salida integer,
    tokens_cache integer
);
CREATE INDEX mod06_uso_ia_solicitado_en ON mod06_uso_ia (solicitado_en);

-- Precio en USD por millón de tokens desde una fecha. Lo mantiene el jefe de sección: los precios cambian.
CREATE TABLE mod06_precio_ia (
    modelo varchar(80) NOT NULL,
    vigente_desde date NOT NULL,
    usd_millon_entrada numeric(12, 4) NOT NULL,
    usd_millon_salida numeric(12, 4) NOT NULL,
    usd_millon_cache numeric(12, 4),
    PRIMARY KEY (modelo, vigente_desde)
);
