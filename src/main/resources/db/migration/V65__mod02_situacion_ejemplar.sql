ALTER TABLE mod02_ejemplar
    ADD COLUMN situacion varchar(12) NOT NULL DEFAULT 'activo'
        CHECK (situacion IN ('activo', 'retirado', 'muerto', 'reemplazado', 'trasladado')),
    ADD COLUMN fecha_situacion date;

CREATE TABLE mod02_historial_situacion_ejemplar (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ejemplar_id bigint NOT NULL REFERENCES mod02_ejemplar (id) ON DELETE CASCADE,
    situacion_anterior varchar(12) NOT NULL,
    situacion_nueva varchar(12) NOT NULL,
    fecha date NOT NULL,
    fecha_registro timestamptz NOT NULL DEFAULT now(),
    motivo varchar(500) NOT NULL,
    usuario_id bigint NOT NULL REFERENCES core_usuario (id),
    ubicacion_anterior varchar(200),
    ubicacion_nueva varchar(200),
    punto_anterior geometry(Point, 4326),
    punto_nuevo geometry(Point, 4326),
    area_anterior_id bigint,
    area_nueva_id bigint
);

CREATE INDEX mod02_historial_situacion_ejemplar_idx
    ON mod02_historial_situacion_ejemplar (ejemplar_id, fecha DESC, id DESC);
