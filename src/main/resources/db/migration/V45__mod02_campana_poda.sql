-- AV-308 · MOD-02: campaña anual de poda mayor y su lista de ejemplares (HU-MOD02-021, RF-POD-001,
-- RN-011, RN-018). Modelo de BD v1, sección 4.2.17 (CampanaPoda) y RI-31. Añade al modelo la lista de
-- ejemplares, la clase de campaña (la HU admite una extraordinaria), el objetivo diario y el estado
-- Borrador. atencion_id queda nulo hasta vincular el requerimiento tercerizado.
CREATE TABLE mod02_campana_poda (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    anio integer NOT NULL,
    nombre varchar(100) NOT NULL,
    clase varchar(16) NOT NULL DEFAULT 'Anual' CHECK (clase IN ('Anual', 'Extraordinaria')),
    motivo_extraordinaria varchar(300),
    fecha_inicio date NOT NULL,
    fecha_fin date NOT NULL,
    objetivo_diario integer NOT NULL CHECK (objetivo_diario > 0),
    estado varchar(16) NOT NULL DEFAULT 'Borrador'
        CHECK (estado IN ('Borrador', 'Planificada', 'EnEjecucion', 'Finalizada')),
    atencion_id bigint REFERENCES mod05_atenciontercerizada (id),
    activo boolean NOT NULL DEFAULT true,
    fecha_creacion timestamptz NOT NULL DEFAULT now(),
    usuario_creacion_id bigint NOT NULL REFERENCES core_usuario (id),
    fecha_modificacion timestamptz NOT NULL DEFAULT now(),
    usuario_modificacion_id bigint NOT NULL REFERENCES core_usuario (id),
    CONSTRAINT mod02_campana_fechas CHECK (fecha_fin >= fecha_inicio),
    CONSTRAINT mod02_campana_motivo CHECK (clase <> 'Extraordinaria' OR motivo_extraordinaria IS NOT NULL)
);

-- RI-31: una sola campaña anual por año; las extraordinarias quedan fuera.
CREATE UNIQUE INDEX mod02_campana_anual_unica ON mod02_campana_poda (anio)
    WHERE clase = 'Anual' AND activo;

CREATE TABLE mod02_campana_ejemplar (
    campana_id bigint NOT NULL REFERENCES mod02_campana_poda (id),
    ejemplar_id bigint NOT NULL REFERENCES mod02_ejemplar (id),
    PRIMARY KEY (campana_id, ejemplar_id)
);

CREATE INDEX mod02_campana_ejemplar_ejemplar ON mod02_campana_ejemplar (ejemplar_id);
