-- AV-255 (RF-PLA-008 y 009, CU-006 y CU-007): las alertas de planificación se guardan con su estado
-- (Abierta o Atendida) para registrar el motivo o la acción al atenderlas. Las genera un proceso
-- periódico. `referencia` distingue cada episodio: para la frecuencia, el fin del último ciclo
-- completado; para la duración, el ciclo.

CREATE TABLE mod03_alerta (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo varchar(20) NOT NULL CHECK (tipo IN ('FrecuenciaProxima', 'DuracionProxima', 'DuracionExcedida')),
    tipo_servicio_id bigint NOT NULL REFERENCES mod05_tiposervicio (id) ON DELETE CASCADE,
    programacion_id bigint REFERENCES mod03_programacion_servicio (id) ON DELETE CASCADE,
    referencia varchar(20) NOT NULL,
    dias integer NOT NULL,
    mensaje varchar(300) NOT NULL,
    estado varchar(10) NOT NULL DEFAULT 'Abierta' CHECK (estado IN ('Abierta', 'Atendida')),
    fecha_generacion timestamptz NOT NULL DEFAULT now(),
    motivo varchar(300),
    atendida_por_id bigint REFERENCES mod05_usuario (id),
    fecha_atencion timestamptz,
    CONSTRAINT mod03_alerta_episodio UNIQUE (tipo, tipo_servicio_id, referencia)
);

CREATE INDEX mod03_alerta_abierta ON mod03_alerta (estado, tipo_servicio_id);
