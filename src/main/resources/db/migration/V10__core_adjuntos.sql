-- AV-221 (RF-T-007): fotografías y documentos asociados a actividades, atenciones, incidencias y
-- ejemplares. La base guarda la clave del almacenamiento, nunca una URL (almacenamiento.md).
-- uuid_cliente hace idempotente el reintento de una subida; el índice por hash impide adjuntar dos
-- veces el mismo archivo al mismo registro.

CREATE TABLE core_archivo (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_original varchar(200) NOT NULL,
    tipo_mime varchar(100) NOT NULL,
    tamano_bytes bigint NOT NULL CHECK (tamano_bytes > 0),
    hash_contenido char(64) NOT NULL,
    clave varchar(400) NOT NULL UNIQUE
);

CREATE TABLE core_adjunto (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    uuid_cliente uuid NOT NULL UNIQUE,
    entidad varchar(30) NOT NULL CHECK (entidad IN ('actividad', 'atencion', 'incidencia', 'ejemplar')),
    registro_id bigint NOT NULL,
    archivo_id bigint NOT NULL UNIQUE REFERENCES core_archivo (id),
    hash_contenido char(64) NOT NULL,
    descripcion varchar(200),
    usuario_creacion_id bigint NOT NULL REFERENCES core_usuario (id),
    fecha_creacion timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT core_adjunto_sin_duplicados UNIQUE (entidad, registro_id, hash_contenido)
);

CREATE INDEX core_adjunto_registro ON core_adjunto (entidad, registro_id);
