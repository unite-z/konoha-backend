-- AV-280 (RF-INC-008, RN-019, HU-027 y CU-027): las sencillas del personal propio se resuelven en un
-- día y como máximo en 48 h. La incidencia guarda su capataz responsable (reasignable desde la
-- bandeja; el encargo de AV-277 lo fijará al derivar) y las causas de retraso que anota el jefe.

ALTER TABLE mod03_incidencia ADD COLUMN capataz_id bigint REFERENCES mod04_personal (id);

CREATE TABLE mod03_causa_retraso (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    incidencia_id bigint NOT NULL REFERENCES mod03_incidencia (id),
    causa varchar(300) NOT NULL CHECK (length(trim(causa)) > 0),
    usuario_id bigint NOT NULL REFERENCES core_usuario (id),
    fecha_hora timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX mod03_causa_retraso_ciclo ON mod03_causa_retraso (incidencia_id, fecha_hora);
