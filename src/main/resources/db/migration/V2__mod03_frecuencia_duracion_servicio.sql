-- AV-7 · MOD-03: frecuencia por estación y duración máxima de los servicios periódicos
-- (HU-MOD03-001 y HU-MOD03-002, RF-PLA-001 y RF-PLA-002).
-- TipoServicio es de MOD-03 según el Modelo de BD v1, pero hoy vive en mod05_tiposervicio (deuda de V1).
-- Para no duplicarlo, MOD-03 le añade sus atributos y lo referencia.
ALTER TABLE mod05_tiposervicio ADD COLUMN es_periodico boolean NOT NULL DEFAULT false;
ALTER TABLE mod05_tiposervicio ADD COLUMN es_ruidoso boolean NOT NULL DEFAULT false;

-- Valores del catálogo de referencia (documentos de la contraparte). Idempotente.
UPDATE mod05_tiposervicio SET es_periodico = true
WHERE nombre IN ('Corte de césped', 'Control fitosanitario', 'Poda mayor programada');
UPDATE mod05_tiposervicio SET es_ruidoso = true WHERE nombre = 'Corte de césped';

CREATE TABLE mod03_frecuencia_servicio (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo_servicio_id bigint NOT NULL REFERENCES mod05_tiposervicio (id),
    estacion varchar(10) NOT NULL CHECK (estacion IN ('Verano', 'Otoño', 'Invierno', 'Primavera')),
    frecuencia_teorica_dias integer NOT NULL CHECK (frecuencia_teorica_dias > 0),
    frecuencia_practica_dias integer CHECK (frecuencia_practica_dias > 0),
    frecuencia_maxima_dias integer CHECK (frecuencia_maxima_dias > 0),
    fecha_creacion timestamptz NOT NULL DEFAULT now(),
    usuario_creacion_id bigint NOT NULL REFERENCES mod05_usuario (id),
    fecha_modificacion timestamptz NOT NULL DEFAULT now(),
    usuario_modificacion_id bigint NOT NULL REFERENCES mod05_usuario (id),
    CONSTRAINT mod03_frecuencia_unica UNIQUE (tipo_servicio_id, estacion),
    -- La máxima nunca es menor que la habitual (la práctica o, si no hay, la teórica).
    CONSTRAINT mod03_frecuencia_maxima CHECK (frecuencia_maxima_dias IS NULL
        OR frecuencia_maxima_dias >= coalesce(frecuencia_practica_dias, frecuencia_teorica_dias))
);

CREATE TABLE mod03_duracion_servicio (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo_servicio_id bigint NOT NULL UNIQUE REFERENCES mod05_tiposervicio (id),
    duracion_maxima_dias integer NOT NULL CHECK (duracion_maxima_dias > 0),
    dias_limpieza integer CHECK (dias_limpieza >= 0),
    hora_inicio time,
    hora_fin time,
    fecha_creacion timestamptz NOT NULL DEFAULT now(),
    usuario_creacion_id bigint NOT NULL REFERENCES mod05_usuario (id),
    fecha_modificacion timestamptz NOT NULL DEFAULT now(),
    usuario_modificacion_id bigint NOT NULL REFERENCES mod05_usuario (id),
    CONSTRAINT mod03_duracion_horario CHECK (hora_inicio IS NULL OR hora_fin IS NULL OR hora_fin > hora_inicio)
);
