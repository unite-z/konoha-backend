-- AV-129 (RF-INV-004, HU-MOD02-009): ruta de jardines del corte de césped. La ruta son los jardines
-- (áreas verdes activas) de los sectores ordinarios, como ya la propone MOD-03, menos los retirados.
-- Un retiro lleva motivo y la fecha desde la que se aplica: los ciclos que empiezan ese día o después
-- ya no copian el jardín; los programados antes conservan su copia. Nada se borra: reincorporar cierra
-- el retiro con su fecha y motivo, y el historial queda completo.

CREATE TABLE mod02_ruta_corte_retiro (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    area_verde_id bigint NOT NULL REFERENCES mod02_area_verde (id),
    desde date NOT NULL,
    motivo varchar(300) NOT NULL CHECK (btrim(motivo) <> ''),
    usuario_id bigint NOT NULL REFERENCES core_usuario (id),
    fecha_registro timestamptz NOT NULL DEFAULT now(),
    reincorporado_desde date,
    motivo_reincorporacion varchar(300),
    usuario_reincorporacion_id bigint REFERENCES core_usuario (id),
    CONSTRAINT mod02_ruta_corte_reincorporacion CHECK (
        reincorporado_desde IS NULL OR reincorporado_desde >= desde)
);

-- Un solo retiro abierto por jardín.
CREATE UNIQUE INDEX mod02_ruta_corte_retiro_abierto
    ON mod02_ruta_corte_retiro (area_verde_id) WHERE reincorporado_desde IS NULL;
CREATE INDEX mod02_ruta_corte_retiro_area ON mod02_ruta_corte_retiro (area_verde_id, desde);
