-- AV-104, AV-111, AV-166 y AV-172: referencias operativas para áreas verdes.
CREATE TABLE mod02_tipo_uso (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre varchar(80) NOT NULL,
    activo boolean NOT NULL DEFAULT true,
    fecha_creacion timestamptz NOT NULL DEFAULT now(),
    usuario_creacion_id bigint REFERENCES mod05_usuario(id),
    fecha_modificacion timestamptz NOT NULL DEFAULT now(),
    usuario_modificacion_id bigint REFERENCES mod05_usuario(id),
    CONSTRAINT mod02_tipo_uso_nombre_no_vacio CHECK (length(trim(nombre)) > 0)
);
CREATE UNIQUE INDEX mod02_tipo_uso_nombre_unico ON mod02_tipo_uso (lower(nombre));

INSERT INTO mod02_tipo_uso (nombre) VALUES
    ('Recreativo'), ('Institucional'), ('Ornamental'), ('Deportivo');

CREATE TABLE mod02_cuartel (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    numero varchar(40) NOT NULL UNIQUE,
    nombre varchar(120) NOT NULL,
    estado varchar(20) NOT NULL DEFAULT 'vigente'
        CHECK (estado IN ('vigente', 'desaparecido')),
    fecha_creacion timestamptz NOT NULL DEFAULT now(),
    usuario_creacion_id bigint REFERENCES mod05_usuario(id),
    fecha_modificacion timestamptz NOT NULL DEFAULT now(),
    usuario_modificacion_id bigint REFERENCES mod05_usuario(id),
    CONSTRAINT mod02_cuartel_nombre_no_vacio CHECK (length(trim(nombre)) > 0)
);

CREATE TABLE mod02_sector (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre varchar(120) NOT NULL,
    activo boolean NOT NULL DEFAULT true,
    atencion_a_demanda boolean NOT NULL DEFAULT false,
    fecha_creacion timestamptz NOT NULL DEFAULT now(),
    usuario_creacion_id bigint NOT NULL REFERENCES mod05_usuario(id),
    fecha_modificacion timestamptz NOT NULL DEFAULT now(),
    usuario_modificacion_id bigint NOT NULL REFERENCES mod05_usuario(id),
    CONSTRAINT mod02_sector_nombre_no_vacio CHECK (length(trim(nombre)) > 0)
);
CREATE UNIQUE INDEX mod02_sector_nombre_activo_unico
    ON mod02_sector (lower(nombre)) WHERE activo;

ALTER TABLE mod02_area_verde
    ADD COLUMN tipo_uso_id bigint REFERENCES mod02_tipo_uso(id) ON DELETE RESTRICT,
    ADD COLUMN cuartel_id bigint REFERENCES mod02_cuartel(id) ON DELETE RESTRICT;

CREATE TABLE mod02_historial_area_sector (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    area_verde_id bigint NOT NULL REFERENCES mod02_area_verde(id) ON DELETE RESTRICT,
    sector_id bigint NOT NULL REFERENCES mod02_sector(id) ON DELETE RESTRICT,
    fecha_inicio timestamptz NOT NULL DEFAULT now(),
    fecha_fin timestamptz,
    usuario_id bigint NOT NULL REFERENCES mod05_usuario(id),
    CHECK (fecha_fin IS NULL OR fecha_fin >= fecha_inicio)
);
CREATE UNIQUE INDEX mod02_historial_area_sector_actual_unico
    ON mod02_historial_area_sector (area_verde_id) WHERE fecha_fin IS NULL;
CREATE INDEX mod02_historial_area_sector_busqueda
    ON mod02_historial_area_sector (sector_id, fecha_inicio DESC);

CREATE TABLE mod02_historial_capataz_sector (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sector_id bigint NOT NULL REFERENCES mod02_sector(id) ON DELETE RESTRICT,
    capataz_id bigint NOT NULL REFERENCES mod05_usuario(id) ON DELETE RESTRICT,
    fecha_inicio timestamptz NOT NULL DEFAULT now(),
    fecha_fin timestamptz,
    usuario_id bigint NOT NULL REFERENCES mod05_usuario(id),
    CHECK (fecha_fin IS NULL OR fecha_fin >= fecha_inicio)
);
CREATE UNIQUE INDEX mod02_historial_capataz_sector_actual_unico
    ON mod02_historial_capataz_sector (sector_id) WHERE fecha_fin IS NULL;
CREATE INDEX mod02_historial_capataz_sector_busqueda
    ON mod02_historial_capataz_sector (capataz_id, fecha_inicio DESC);
