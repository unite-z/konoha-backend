-- AV-166: catálogo de sectores y asignaciones históricas de áreas.
CREATE TABLE mod02_sector (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre varchar(120) NOT NULL,
    activo boolean NOT NULL DEFAULT true,
    atencion_a_demanda boolean NOT NULL DEFAULT false,
    fecha_creacion timestamptz NOT NULL DEFAULT now(),
    usuario_creacion_id bigint NOT NULL REFERENCES core_usuario(id),
    fecha_modificacion timestamptz NOT NULL DEFAULT now(),
    usuario_modificacion_id bigint NOT NULL REFERENCES core_usuario(id),
    CONSTRAINT mod02_sector_nombre_no_vacio CHECK (length(trim(nombre)) > 0)
);
CREATE UNIQUE INDEX mod02_sector_nombre_activo_unico
    ON mod02_sector (lower(nombre)) WHERE activo;

CREATE TABLE mod02_historial_area_sector (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    area_verde_id bigint NOT NULL REFERENCES mod02_area_verde(id) ON DELETE RESTRICT,
    sector_id bigint NOT NULL REFERENCES mod02_sector(id) ON DELETE RESTRICT,
    fecha_inicio timestamptz NOT NULL DEFAULT now(),
    fecha_fin timestamptz,
    usuario_id bigint NOT NULL REFERENCES core_usuario(id),
    CHECK (fecha_fin IS NULL OR fecha_fin >= fecha_inicio)
);
CREATE UNIQUE INDEX mod02_historial_area_sector_actual_unico
    ON mod02_historial_area_sector (area_verde_id) WHERE fecha_fin IS NULL;
CREATE INDEX mod02_historial_area_sector_busqueda
    ON mod02_historial_area_sector (sector_id, fecha_inicio DESC);
