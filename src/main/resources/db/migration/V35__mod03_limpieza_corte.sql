-- AV-262 (RF-COR-006, RN-002, HU-014 y CU-014): la limpieza cuenta dentro del ciclo de corte y solo
-- se registra con la ruta completa. Cada jornada guarda su fecha y su autor.

CREATE TABLE mod03_limpieza_corte (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    programacion_id bigint NOT NULL REFERENCES mod03_programacion_servicio (id) ON DELETE CASCADE,
    fecha date NOT NULL,
    usuario_id bigint NOT NULL REFERENCES core_usuario (id),
    fecha_registro timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT mod03_limpieza_corte_dia UNIQUE (programacion_id, fecha)
);
