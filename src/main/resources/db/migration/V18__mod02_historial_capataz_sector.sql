-- AV-302: historial del capataz responsable por sector.
CREATE TABLE mod02_historial_capataz_sector (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sector_id bigint NOT NULL REFERENCES mod02_sector(id) ON DELETE RESTRICT,
    capataz_id bigint NOT NULL REFERENCES core_usuario(id) ON DELETE RESTRICT,
    fecha_inicio timestamptz NOT NULL DEFAULT now(),
    fecha_fin timestamptz,
    usuario_id bigint NOT NULL REFERENCES core_usuario(id),
    CHECK (fecha_fin IS NULL OR fecha_fin >= fecha_inicio)
);
CREATE UNIQUE INDEX mod02_historial_capataz_sector_actual_unico
    ON mod02_historial_capataz_sector (sector_id) WHERE fecha_fin IS NULL;
CREATE INDEX mod02_historial_capataz_sector_busqueda
    ON mod02_historial_capataz_sector (capataz_id, fecha_inicio DESC);
