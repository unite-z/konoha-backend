-- AV-264 (HU-009 «avisa a quien ejecuta»; ADR 0003: solo dentro de la aplicación): registro mínimo
-- de avisos con destinatario (un usuario o un proveedor, que aún no tiene cuenta), texto, origen y
-- si se leyó. Lo reutiliza AV-281 para las incidencias.

CREATE TABLE mod03_aviso (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    destinatario_usuario_id bigint REFERENCES core_usuario (id),
    destinatario_proveedor_id bigint REFERENCES mod05_proveedor (id),
    texto varchar(300) NOT NULL CHECK (length(trim(texto)) > 0),
    origen varchar(30) NOT NULL,
    origen_id bigint NOT NULL,
    leido boolean NOT NULL DEFAULT false,
    fecha_hora timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT mod03_aviso_destinatario
        CHECK ((destinatario_usuario_id IS NULL) <> (destinatario_proveedor_id IS NULL))
);

CREATE INDEX mod03_aviso_usuario ON mod03_aviso (destinatario_usuario_id, leido, fecha_hora DESC);

ALTER TABLE mod03_interrupcion_corte ADD COLUMN aviso_id bigint REFERENCES mod03_aviso (id);
