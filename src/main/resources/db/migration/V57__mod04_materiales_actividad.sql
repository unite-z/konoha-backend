CREATE TABLE mod04_material_actividad (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 actividad_id bigint NOT NULL REFERENCES mod04_actividad(id),
 material_id bigint REFERENCES mod04_material_catalogo(id),
 descripcion_otro varchar(150),
 cantidad numeric(12,2) NOT NULL CHECK (cantidad > 0),
 unidad_medida_id bigint NOT NULL REFERENCES mod04_unidad_medida(id),
 origen varchar(150),
 destino varchar(150),
 usuario_creacion_id bigint NOT NULL REFERENCES core_usuario(id),
 fecha_creacion timestamptz NOT NULL DEFAULT now(),
 CHECK ((material_id IS NULL) <> (descripcion_otro IS NULL)),
 CHECK ((origen IS NULL) = (destino IS NULL))
);
CREATE INDEX mod04_material_actividad_actividad ON mod04_material_actividad(actividad_id);
