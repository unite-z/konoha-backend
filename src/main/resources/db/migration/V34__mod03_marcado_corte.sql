-- AV-260 (RF-COR-002, HU-011 y CU-011): el capataz marca los jardines cortados de su ruta, también
-- desde la cola sin conexión (la clave de idempotencia evita duplicar un reenvío), anota
-- observaciones y registra los jardines que se cortaron fuera de ruta, con nota obligatoria.

ALTER TABLE mod03_ruta_corte
    ADD COLUMN clave_idempotencia uuid,
    ADD COLUMN sincronizado_en timestamptz;

CREATE TABLE mod03_observacion_jardin (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ruta_corte_id bigint NOT NULL REFERENCES mod03_ruta_corte (id) ON DELETE CASCADE,
    texto varchar(300) NOT NULL CHECK (length(trim(texto)) > 0),
    usuario_id bigint NOT NULL REFERENCES core_usuario (id),
    fecha_hora timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE mod03_fuera_de_ruta (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    programacion_id bigint NOT NULL REFERENCES mod03_programacion_servicio (id) ON DELETE CASCADE,
    area_verde_id bigint NOT NULL REFERENCES mod02_area_verde (id),
    nota varchar(300) NOT NULL CHECK (length(trim(nota)) > 0),
    marcado_en timestamptz NOT NULL,
    marcado_por_id bigint NOT NULL REFERENCES core_usuario (id),
    clave_idempotencia uuid UNIQUE,
    fecha_hora timestamptz NOT NULL DEFAULT now()
);
