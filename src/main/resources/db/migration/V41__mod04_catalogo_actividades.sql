ALTER TABLE mod04_tipo_actividad ADD COLUMN clase_id bigint NOT NULL DEFAULT 3
 REFERENCES mod04_clase_actividad(id);
CREATE UNIQUE INDEX mod04_tipo_actividad_clase_nombre
 ON mod04_tipo_actividad(clase_id,lower(trim(nombre)));
ALTER TABLE mod04_tipo_actividad ADD CONSTRAINT mod04_tipo_actividad_nombre_valido
 CHECK (length(trim(nombre)) > 0);

ALTER TABLE mod04_actividad ADD COLUMN tipo_actividad_nombre varchar(150);
UPDATE mod04_actividad a SET tipo_actividad_nombre=t.nombre
 FROM mod04_tipo_actividad t WHERE t.id=a.tipo_actividad_id;
CREATE FUNCTION mod04_fijar_nombre_tipo() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 SELECT nombre INTO NEW.tipo_actividad_nombre FROM mod04_tipo_actividad
 WHERE id=NEW.tipo_actividad_id;
 RETURN NEW;
END;
$$;
CREATE TRIGGER mod04_actividad_nombre_historico BEFORE INSERT ON mod04_actividad
 FOR EACH ROW EXECUTE FUNCTION mod04_fijar_nombre_tipo();
