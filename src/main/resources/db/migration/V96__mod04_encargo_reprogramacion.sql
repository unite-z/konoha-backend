-- AV-405: reprogramar un encargo vivo (cambiar su periodo y su plazo) con justificación e historial.
CREATE TABLE mod04_encargo_reprogramacion (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    encargo_id bigint NOT NULL REFERENCES mod04_encargo (id),
    fecha_inicio_anterior date NOT NULL,
    fecha_fin_anterior date NOT NULL,
    plazo_anterior date NOT NULL,
    fecha_inicio_nueva date NOT NULL,
    fecha_fin_nueva date NOT NULL,
    plazo_nuevo date NOT NULL,
    justificacion varchar(1000) NOT NULL CHECK (btrim(justificacion) <> ''),
    usuario_id bigint NOT NULL REFERENCES core_usuario (id),
    fecha timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX mod04_encargo_reprogramacion_encargo_idx
    ON mod04_encargo_reprogramacion (encargo_id, id);
