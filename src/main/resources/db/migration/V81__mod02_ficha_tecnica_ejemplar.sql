-- AV-133 · MOD-02: ficha técnica del ejemplar (RF-INV-005, HU-MOD02-011 y HU-MOD02-012).
-- Datos dasométricos además de la altura total (V59), origen y estado de salud. Sin ninguna medida,
-- el ejemplar se muestra como pendiente de medir (se calcula, no se guarda).
ALTER TABLE mod02_ejemplar
    ADD COLUMN altura_fuste_m numeric(6, 2) CHECK (altura_fuste_m > 0),
    ADD COLUMN dap_cm numeric(6, 1) CHECK (dap_cm > 0),
    ADD COLUMN radio_copa_m numeric(5, 2) CHECK (radio_copa_m > 0),
    ADD COLUMN origen varchar(12) CHECK (origen IN ('Nativo', 'Introducido', 'Desconocido')),
    ADD COLUMN estado_salud varchar(8) CHECK (estado_salud IN ('Bueno', 'Regular', 'Malo'));

-- Evaluación fitosanitaria y estructural: hallazgos por criterio o su ausencia explícita, con el
-- manejo recomendado, la fecha y el autor. No se edita: una corrección es otra evaluación.
CREATE TABLE mod02_evaluacion_ejemplar (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ejemplar_id bigint NOT NULL REFERENCES mod02_ejemplar (id),
    fecha date NOT NULL,
    sin_hallazgos boolean NOT NULL DEFAULT false,
    enfermedades_plagas varchar(300),
    danos_mecanicos_zunchado varchar(300),
    inclinacion_ramas_secas varchar(300),
    cavidades_pudricion varchar(300),
    raices_expuestas varchar(300),
    interferencia_infraestructura varchar(300),
    manejo_recomendado varchar(500),
    usuario_id bigint NOT NULL REFERENCES core_usuario (id),
    fecha_creacion timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT mod02_evaluacion_completa CHECK (
        sin_hallazgos
        OR coalesce(enfermedades_plagas, danos_mecanicos_zunchado, inclinacion_ramas_secas,
            cavidades_pudricion, raices_expuestas, interferencia_infraestructura) IS NOT NULL)
);

CREATE INDEX mod02_evaluacion_ejemplar_fecha
    ON mod02_evaluacion_ejemplar (ejemplar_id, fecha DESC, id DESC);
