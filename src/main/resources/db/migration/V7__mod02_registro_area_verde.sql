-- AV-111 / RF-INV-002: inventario inicial de áreas verdes y vínculo al catálogo de coberturas.
CREATE TABLE mod02_area_verde (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre varchar(150) NOT NULL,
    lugar varchar(150) NOT NULL,
    ubicacion varchar(250) NOT NULL,
    superficie_m2 numeric(12, 2) NOT NULL,
    tipo_cobertura_id bigint REFERENCES mod02_cobertura_vegetal(id) ON DELETE RESTRICT,
    activo boolean NOT NULL DEFAULT true,
    fecha_creacion timestamptz NOT NULL DEFAULT now(),
    usuario_creacion_id bigint NOT NULL REFERENCES mod05_usuario(id),
    fecha_modificacion timestamptz NOT NULL DEFAULT now(),
    usuario_modificacion_id bigint NOT NULL REFERENCES mod05_usuario(id),
    CONSTRAINT mod02_area_verde_superficie_positiva CHECK (superficie_m2 > 0)
);

CREATE INDEX mod02_area_verde_nombre_busqueda ON mod02_area_verde (lower(nombre));
CREATE INDEX mod02_area_verde_cobertura ON mod02_area_verde (tipo_cobertura_id);
