-- AV-216 (RF-T-001): sesiones revocables. El token viaja en una cookie HttpOnly y aquí solo se guarda
-- su SHA-256, así que un volcado de la base no permite suplantar a nadie. Desactivar una cuenta o
-- cambiar la contraseña revoca sus sesiones (HU-MOD01-003 y 005).

CREATE TABLE core_sesion (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    token_hash char(64) NOT NULL UNIQUE,
    usuario_id bigint NOT NULL REFERENCES core_usuario (id),
    canal varchar(20) NOT NULL CHECK (canal IN ('oficina', 'campo')),
    persistente boolean NOT NULL DEFAULT false,
    creada timestamptz NOT NULL DEFAULT now(),
    ultima_actividad timestamptz NOT NULL DEFAULT now(),
    expira timestamptz NOT NULL,
    revocada timestamptz,
    motivo_revocacion varchar(60)
);

CREATE INDEX core_sesion_usuario_vigente ON core_sesion (usuario_id) WHERE revocada IS NULL;
