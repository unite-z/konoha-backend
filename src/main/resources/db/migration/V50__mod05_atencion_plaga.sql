-- RF-FIT-004: plagas controladas en cada aplicación (atención), del mismo catálogo de mod05_plaga
-- que ya usa la atención especial (RF-INV-011).
CREATE TABLE mod05_atencion_plaga (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 atencion_id bigint NOT NULL REFERENCES mod05_atenciontercerizada(id),
 plaga_id bigint NOT NULL REFERENCES mod05_plaga(id),
 CONSTRAINT mod05_atencion_plaga_unico UNIQUE (atencion_id, plaga_id)
);
CREATE INDEX mod05_atencion_plaga_atencion ON mod05_atencion_plaga (atencion_id);
CREATE INDEX mod05_atencion_plaga_plaga ON mod05_atencion_plaga (plaga_id);
