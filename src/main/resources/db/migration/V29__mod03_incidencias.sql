-- AV-274 (RF-INC-001, HU-020, CU-020): incidencias de MOD-03. Cualquier usuario reporta una desde la
-- app; la oficina la registra en nombre de otra persona con su canal. Ubicación en las áreas verdes
-- de MOD-02; foto en los adjuntos de MOD-01 (entidad «incidencia»). Historial de transiciones con
-- autor, o sin autor si es del sistema.

CREATE TABLE mod03_tipo_incidencia (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre varchar(80) NOT NULL UNIQUE,
    -- Incidencia sencilla (RN-019): plazo objetivo de 1 día y máximo de 48 h.
    sencilla boolean NOT NULL DEFAULT false,
    activo boolean NOT NULL DEFAULT true
);

INSERT INTO mod03_tipo_incidencia (nombre, sencilla) VALUES
    ('Rama caída', true),
    ('Rama colgante', true),
    ('Poda de ramas', true),
    ('Hojarasca en exceso', true),
    ('Basura en jardín', true),
    ('Césped dañado', true),
    ('Árbol inclinado', false),
    ('Riego averiado', false),
    ('Plaga o enfermedad', false)
ON CONFLICT (nombre) DO NOTHING;

CREATE SEQUENCE mod03_incidencia_numero_seq;

CREATE TABLE mod03_incidencia (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo varchar(20) NOT NULL UNIQUE,
    tipo_incidencia_id bigint NOT NULL REFERENCES mod03_tipo_incidencia (id),
    area_verde_id bigint NOT NULL REFERENCES mod02_area_verde (id),
    ejemplar_id bigint REFERENCES mod02_ejemplar (id),
    descripcion varchar(300) NOT NULL DEFAULT '',
    canal varchar(12) NOT NULL
        CHECK (canal IN ('App', 'Web', 'Telefono', 'WhatsApp', 'Correo', 'Presencial')),
    reportante_usuario_id bigint REFERENCES core_usuario (id),
    reportante_nombre varchar(120),
    reportante_contacto varchar(120),
    estado varchar(20) NOT NULL DEFAULT 'Registrada'
        CHECK (estado IN ('Registrada', 'Clasificada', 'DerivadaInterna', 'DerivadaTercerizada',
            'EnAtencion', 'Atendida', 'Cerrada', 'Descartada')),
    severidad varchar(5) CHECK (severidad IN ('Alta', 'Media', 'Baja')),
    impacto varchar(5) CHECK (impacto IN ('Alto', 'Medio', 'Bajo')),
    via varchar(15) CHECK (via IN ('PersonalPropio', 'Tercerizada')),
    registrada_por_id bigint NOT NULL REFERENCES core_usuario (id),
    fecha_registro timestamptz NOT NULL DEFAULT now(),
    fecha_cierre timestamptz,
    -- Envíos diferidos sin conexión: la misma clave devuelve la misma incidencia.
    clave_idempotencia uuid UNIQUE,
    CONSTRAINT mod03_incidencia_reportante
        CHECK (reportante_usuario_id IS NOT NULL OR length(trim(reportante_nombre)) > 0)
);

CREATE INDEX mod03_incidencia_estado ON mod03_incidencia (estado, fecha_registro DESC);
CREATE INDEX mod03_incidencia_reportante_idx ON mod03_incidencia (reportante_usuario_id);

CREATE TABLE mod03_historial_incidencia (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    incidencia_id bigint NOT NULL REFERENCES mod03_incidencia (id),
    estado varchar(20) NOT NULL,
    fecha_hora timestamptz NOT NULL DEFAULT now(),
    -- Sin usuario: transición automática del sistema.
    usuario_id bigint REFERENCES core_usuario (id),
    detalle varchar(300)
);

CREATE INDEX mod03_historial_incidencia_ciclo ON mod03_historial_incidencia (incidencia_id, fecha_hora);
