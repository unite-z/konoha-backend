-- AV-275 (HU-020 escenario 2): si ya hay una incidencia abierta del mismo tipo en el mismo ejemplar
-- o espacio, el reportante añade su información a la existente en lugar de duplicarla. Cada
-- reporte sumado guarda quién, cuándo y su descripción; la foto va a los adjuntos de MOD-01.

CREATE TABLE mod03_reporte_incidencia (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    incidencia_id bigint NOT NULL REFERENCES mod03_incidencia (id),
    usuario_id bigint NOT NULL REFERENCES core_usuario (id),
    descripcion varchar(300) NOT NULL DEFAULT '',
    fecha_hora timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX mod03_reporte_incidencia_ciclo ON mod03_reporte_incidencia (incidencia_id, fecha_hora);
