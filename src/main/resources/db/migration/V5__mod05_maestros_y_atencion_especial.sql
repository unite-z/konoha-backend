-- Ejemplares marcados con atención fitosanitaria especial. Un ejemplar se marca una sola vez.
CREATE TABLE mod05_atencion_especial (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 ejemplar_id bigint NOT NULL UNIQUE REFERENCES mod05_ejemplar(id),
 plaga_id bigint NOT NULL REFERENCES mod05_plaga(id),
 aplicaciones_adicionales smallint NOT NULL CONSTRAINT mod05_especial_adicionales CHECK (aplicaciones_adicionales IN (1, 2)),
 aplicaciones_realizadas smallint NOT NULL DEFAULT 0,
 fecha_creacion timestamp with time zone NOT NULL,
 usuario_creacion_id bigint NOT NULL REFERENCES mod05_usuario(id),
 CONSTRAINT mod05_especial_realizadas CHECK (aplicaciones_realizadas >= 0 AND aplicaciones_realizadas <= aplicaciones_adicionales)
);
CREATE INDEX mod05_atencion_especial_plaga ON mod05_atencion_especial (plaga_id);
