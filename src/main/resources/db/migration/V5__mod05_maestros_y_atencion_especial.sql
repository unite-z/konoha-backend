-- Datos adicionales del proveedor (contacto y vínculo con otras empresas). Un proveedor sin fila aquí
-- (por ejemplo, el precargado) se interpreta como «sin vínculo» y sin contacto.
CREATE TABLE mod05_proveedor_detalle (
 proveedor_id bigint PRIMARY KEY REFERENCES mod05_proveedor(id),
 contacto varchar(200) NOT NULL DEFAULT '',
 tipo_vinculo varchar(20) NOT NULL DEFAULT 'SinVinculo'
  CONSTRAINT mod05_vinculo_tipo CHECK (tipo_vinculo IN ('SinVinculo','Principal','Subsidiaria','Vinculada')),
 proveedor_relacionado_id bigint NULL REFERENCES mod05_proveedor(id),
 CONSTRAINT mod05_vinculo_relacionado CHECK (
  (tipo_vinculo IN ('SinVinculo','Principal') AND proveedor_relacionado_id IS NULL)
  OR (tipo_vinculo IN ('Subsidiaria','Vinculada') AND proveedor_relacionado_id IS NOT NULL AND proveedor_relacionado_id <> proveedor_id))
);
CREATE INDEX mod05_proveedor_detalle_relacionado ON mod05_proveedor_detalle (proveedor_relacionado_id);

-- Condiciones económicas y de servicio del contrato. Los contratos precargados no tienen fila.
CREATE SEQUENCE mod05_contrato_numero_seq;
CREATE TABLE mod05_contrato_detalle (
 contrato_id bigint PRIMARY KEY REFERENCES mod05_contrato(id),
 area_metrado_estimado varchar(120) NOT NULL,
 monto_fijo numeric(12, 2) NOT NULL CONSTRAINT mod05_contrato_monto CHECK (monto_fijo >= 0),
 frecuencia_pactada varchar(120) NOT NULL,
 condiciones text NOT NULL DEFAULT '',
 fecha_creacion timestamp with time zone NOT NULL,
 usuario_creacion_id bigint NOT NULL REFERENCES mod05_usuario(id)
);

-- Catálogo de plagas (RF-INV-011). El catálogo completo se mantiene en el control fitosanitario (HU-MOD05-020).
CREATE TABLE mod05_plaga (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 nombre varchar(120) NOT NULL UNIQUE,
 activo boolean NOT NULL DEFAULT true
);
