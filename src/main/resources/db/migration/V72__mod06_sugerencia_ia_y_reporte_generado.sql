-- AV-291 (RF-IA-001, RN-IA-001) y AV-295 (RF-REP-009): tablas propias de MOD-06 (Modelo BD 4.6.2 y 4.6.3).
-- Sustituyen a mock-data/mod06/SugerenciaIA.json y ReporteGenerado.json, que vivían dentro del contenedor y se
-- perdían en cada despliegue. MOD-06 solo escribe aquí; el resto de módulos se lee o se invoca por su servicio.

-- Sugerencia de IA: una por análisis solicitado. La entrada, la salida de la IA y la decisión de quien revisa
-- se guardan en «contenido» (JSON tipado por pantalla, versionado con contenido.version_contenido).
CREATE TABLE mod06_sugerencia_ia (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo varchar(40) NOT NULL CHECK (tipo IN ('ExtraccionReporte', 'Priorizacion', 'Inconsistencia', 'Cronograma',
        'EstimacionRecursos', 'ClasificacionIncidencia', 'EvidenciaFitosanitaria')),
    -- Registro oficial al que se refiere (p. ej. ReporteProveedor 12, Incidencia 7). Puede faltar en un análisis
    -- que no parte de un registro concreto (priorización, cronograma).
    entidad varchar(60),
    registro_id bigint,
    archivo_id bigint,
    contenido jsonb NOT NULL DEFAULT '{}'::jsonb,
    estado varchar(10) NOT NULL DEFAULT 'Propuesta' CHECK (estado IN ('Propuesta', 'Validada', 'Rechazada')),
    validador_id bigint REFERENCES core_usuario (id),
    fecha_validacion timestamptz,
    fecha_creacion timestamptz NOT NULL DEFAULT now(),
    usuario_creacion_id bigint NOT NULL REFERENCES core_usuario (id),
    fecha_modificacion timestamptz NOT NULL DEFAULT now(),
    usuario_modificacion_id bigint NOT NULL REFERENCES core_usuario (id),
    CONSTRAINT mod06_sugerencia_ia_registro CHECK ((entidad IS NULL) = (registro_id IS NULL)),
    -- RI-32: solo una sugerencia revisada tiene validador y fecha de validación.
    CONSTRAINT mod06_sugerencia_ia_revision CHECK (
        (estado = 'Propuesta' AND validador_id IS NULL AND fecha_validacion IS NULL)
        OR (estado <> 'Propuesta' AND validador_id IS NOT NULL AND fecha_validacion IS NOT NULL))
);

CREATE INDEX mod06_sugerencia_ia_bandeja ON mod06_sugerencia_ia (tipo, estado, fecha_creacion DESC, id DESC);
CREATE INDEX mod06_sugerencia_ia_registro_idx ON mod06_sugerencia_ia (entidad, registro_id);

-- Exportación de un reporte (RF-REP-009). Exportar no cambia ningún dato: solo deja constancia del archivo.
CREATE TABLE mod06_reporte_generado (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo varchar(30) NOT NULL CHECK (tipo IN ('GestionOSG', 'ServicioTercerizado', 'MaterialVegetal',
        'DistribucionPersonal', 'MatrizIncidencias', 'Listado')),
    formato varchar(10) NOT NULL CHECK (formato IN ('PDF', 'Excel')),
    parametros jsonb NOT NULL DEFAULT '{}'::jsonb,
    resumen_parametros varchar(300) NOT NULL DEFAULT '',
    filas integer NOT NULL CHECK (filas >= 0),
    -- Clave del archivo en el almacenamiento (ArchivoStorage), nunca una ruta absoluta.
    archivo_clave varchar(300) NOT NULL UNIQUE,
    archivo_nombre varchar(200) NOT NULL,
    archivo_tipo_mime varchar(100) NOT NULL,
    archivo_tamano_bytes bigint NOT NULL CHECK (archivo_tamano_bytes >= 0),
    usuario_id bigint NOT NULL REFERENCES core_usuario (id),
    fecha_hora timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX mod06_reporte_generado_historial ON mod06_reporte_generado (fecha_hora DESC, id DESC);
CREATE INDEX mod06_reporte_generado_tipo ON mod06_reporte_generado (tipo, fecha_hora DESC);
