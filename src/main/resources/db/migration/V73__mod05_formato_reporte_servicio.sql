-- AV-291 (RF-IA-001) y RF-SER-009: formato estándar del informe del proveedor por tipo de servicio
-- (Modelo BD: FormatoReporteServicio y CampoFormatoReporte, entidades de MOD-05). Hasta ahora solo existía en
-- mock-data/mod05/*.json y la extracción con IA lo leía de ahí. La pantalla de configuración de MOD-05
-- (RF-SER-009) escribirá en estas tablas; MOD-06 solo las lee.
CREATE TABLE mod05_formato_reporte_servicio (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo_servicio_id bigint NOT NULL REFERENCES mod05_tiposervicio (id),
    version integer NOT NULL CHECK (version > 0),
    vigente boolean NOT NULL DEFAULT true,
    fecha_creacion timestamptz NOT NULL DEFAULT now(),
    usuario_creacion_id bigint REFERENCES core_usuario (id),
    fecha_modificacion timestamptz NOT NULL DEFAULT now(),
    usuario_modificacion_id bigint REFERENCES core_usuario (id),
    UNIQUE (tipo_servicio_id, version)
);

-- Un único formato vigente por tipo de servicio.
CREATE UNIQUE INDEX mod05_formato_reporte_vigente ON mod05_formato_reporte_servicio (tipo_servicio_id)
    WHERE vigente;

CREATE TABLE mod05_campo_formato_reporte (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    formato_id bigint NOT NULL REFERENCES mod05_formato_reporte_servicio (id),
    orden integer NOT NULL CHECK (orden > 0),
    nombre_campo varchar(100) NOT NULL,
    tipo_dato varchar(20) NOT NULL
        CHECK (tipo_dato IN ('Texto', 'Texto largo', 'Entero', 'Decimal', 'Booleano', 'Fecha', 'JSON')),
    obligatorio boolean NOT NULL DEFAULT false,
    -- Solo en los campos JSON: [{nombre, tipo_dato, descripcion}] de cada elemento de la lista.
    subcampos jsonb,
    UNIQUE (formato_id, orden),
    UNIQUE (formato_id, nombre_campo),
    CONSTRAINT mod05_campo_formato_subcampos CHECK (subcampos IS NULL OR tipo_dato = 'JSON')
);

-- Formato inicial de Control fitosanitario, el mismo que mock-data/mod05/CampoFormatoReporte.json. Si el tipo de
-- servicio aún no existe (base nueva), no carga nada: lo hace la precarga dev (FormatosReporte.precargar).
WITH tipo AS (
    SELECT id FROM mod05_tiposervicio WHERE nombre = 'Control fitosanitario'
), formato AS (
    INSERT INTO mod05_formato_reporte_servicio (tipo_servicio_id, version, vigente)
    SELECT id, 1, true FROM tipo
    ON CONFLICT DO NOTHING
    RETURNING id
)
