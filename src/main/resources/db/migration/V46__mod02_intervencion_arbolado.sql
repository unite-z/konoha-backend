-- AV-309 · MOD-02: registro de poda por ejemplar y evidencia (HU-MOD02-022, RF-POD-002). Modelo de BD
-- v1, secciones 4.2.18 (TipoIntervencion) y 4.2.19 (IntervencionArbolado). Las columnas de poda menor
-- (actividad_id, tipo_actividad_id) y de poda a demanda (motivo, altura) llegan con AV-315 y AV-312.
-- La intervención es verificable si tiene fotografía en core_adjunto: no se guarda un estado aparte.
CREATE TABLE mod02_tipo_intervencion (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre varchar(80) NOT NULL UNIQUE,
    es_poda boolean NOT NULL,
    es_riesgo boolean NOT NULL DEFAULT false,
    activo boolean NOT NULL DEFAULT true
);

-- Catálogo de referencia (RF-POD-006). Idempotente.
INSERT INTO mod02_tipo_intervencion (nombre, es_poda) VALUES
    ('Poda de ramas laterales', true),
    ('Poda de limpieza', true),
    ('Reducción de copa', true),
    ('Extracción', false),
    ('Traslado y reubicación', false)
ON CONFLICT (nombre) DO NOTHING;

-- Unidades que usa el registro de poda; el catálogo sigue siendo de MOD-05.
INSERT INTO mod05_unidadmedida (nombre, simbolo)
SELECT v.nombre, v.simbolo FROM (VALUES ('Rama', 'rama'), ('Ejemplar', 'ejemplar')) v(nombre, simbolo)
WHERE NOT EXISTS (SELECT 1 FROM mod05_unidadmedida u WHERE u.nombre = v.nombre);

CREATE TABLE mod02_intervencion_arbolado (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ejemplar_id bigint NOT NULL REFERENCES mod02_ejemplar (id),
    categoria varchar(16) NOT NULL CHECK (categoria IN ('Menor', 'MayorCampana', 'AlturaDemanda')),
    campana_id bigint REFERENCES mod02_campana_poda (id),
    atencion_id bigint REFERENCES mod05_atenciontercerizada (id),
    incidencia_id bigint REFERENCES mod03_incidencia (id),
    tipo_intervencion_id bigint REFERENCES mod02_tipo_intervencion (id),
    fecha_ejecucion date,
    reduccion_copa_pct numeric(5, 2) CHECK (reduccion_copa_pct BETWEEN 0 AND 100),
    ramas_laterales_cortadas integer CHECK (ramas_laterales_cortadas >= 0),
    cantidad_solicitada numeric(10, 2) CHECK (cantidad_solicitada >= 0),
    cantidad_ejecutada numeric(10, 2) CHECK (cantidad_ejecutada >= 0),
    unidad_medida_id bigint REFERENCES mod05_unidadmedida (id),
    prioridad varchar(5) CHECK (prioridad IN ('Alta', 'Media', 'Baja')),
    activo boolean NOT NULL DEFAULT true,
    fecha_creacion timestamptz NOT NULL DEFAULT now(),
    usuario_creacion_id bigint NOT NULL REFERENCES core_usuario (id),
    fecha_modificacion timestamptz NOT NULL DEFAULT now(),
    usuario_modificacion_id bigint NOT NULL REFERENCES core_usuario (id),
    CONSTRAINT mod02_intervencion_unidad CHECK (
        (cantidad_solicitada IS NULL AND cantidad_ejecutada IS NULL) OR unidad_medida_id IS NOT NULL)
);

CREATE INDEX mod02_intervencion_campana ON mod02_intervencion_arbolado (campana_id) WHERE activo;
CREATE INDEX mod02_intervencion_ejemplar ON mod02_intervencion_arbolado (ejemplar_id, fecha_ejecucion);

-- La fotografía de la intervención se guarda con los adjuntos comunes (RF-T-007).
ALTER TABLE core_adjunto DROP CONSTRAINT core_adjunto_entidad_check;
ALTER TABLE core_adjunto ADD CONSTRAINT core_adjunto_entidad_check
    CHECK (entidad IN ('actividad', 'atencion', 'incidencia', 'ejemplar', 'intervencion'));
