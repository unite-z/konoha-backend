-- AV-18 · MOD-03: programación de servicios y confirmación de restricciones
-- (HU-MOD03-004, 005, 006 y 007; RF-PLA-004, 007, 008 y 009; RN-003).
-- Modelo de BD v1, secciones 4.3.7 (ProgramacionServicio) y 4.3.8 (ConfirmacionRestriccion).
-- Añade fecha_inicio_real y fecha_fin_real para medir la duración en curso (RF-PLA-009).
-- cuadrilla_id queda sin FK hasta que exista la tabla de cuadrillas de MOD-04.
CREATE TABLE mod03_programacion_servicio (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo_servicio_id bigint NOT NULL REFERENCES mod05_tiposervicio (id),
    proveedor_id bigint REFERENCES mod05_proveedor (id),
    cuadrilla_id bigint,
    estacion varchar(10) NOT NULL CHECK (estacion IN ('Verano', 'Otoño', 'Invierno', 'Primavera')),
    fecha_inicio_prevista date NOT NULL,
    fecha_fin_prevista date NOT NULL,
    ventana_mes varchar(7) CHECK (ventana_mes ~ '^[0-9]{4}-(0[1-9]|1[0-2])$'),
    estado varchar(12) NOT NULL DEFAULT 'Programada'
        CHECK (estado IN ('Programada', 'EnCurso', 'Completada', 'Cancelada')),
    fecha_inicio_real date,
    fecha_fin_real date,
    creado_por_id bigint NOT NULL REFERENCES mod05_usuario (id),
    fecha_creacion timestamptz NOT NULL DEFAULT now(),
    usuario_creacion_id bigint NOT NULL REFERENCES mod05_usuario (id),
    fecha_modificacion timestamptz NOT NULL DEFAULT now(),
    usuario_modificacion_id bigint NOT NULL REFERENCES mod05_usuario (id),
    CONSTRAINT mod03_programacion_fechas CHECK (fecha_fin_prevista >= fecha_inicio_prevista),
    CONSTRAINT mod03_programacion_real CHECK (fecha_fin_real IS NULL
        OR (fecha_inicio_real IS NOT NULL AND fecha_fin_real >= fecha_inicio_real))
);

CREATE INDEX mod03_programacion_periodo
    ON mod03_programacion_servicio (fecha_inicio_prevista, fecha_fin_prevista);
CREATE INDEX mod03_programacion_servicio_estado ON mod03_programacion_servicio (tipo_servicio_id, estado);

CREATE TABLE mod03_confirmacion_restriccion (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    programacion_id bigint NOT NULL REFERENCES mod03_programacion_servicio (id),
    restriccion_id bigint NOT NULL REFERENCES mod03_restriccion_calendario (id),
    usuario_id bigint NOT NULL REFERENCES mod05_usuario (id),
    fecha_hora timestamptz NOT NULL DEFAULT now(),
    justificacion varchar(300) NOT NULL CHECK (length(trim(justificacion)) > 0),
    CONSTRAINT mod03_confirmacion_unica UNIQUE (programacion_id, restriccion_id)
);
