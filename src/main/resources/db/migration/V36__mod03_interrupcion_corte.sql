-- AV-258 (HU-009, CU-009, RN-004): el jefe detiene el corte en una zona por molestia académica y lo
-- traslada a otra zona pendiente de la ruta. El tiempo detenido (de la hora de la interrupción al
-- fin de la jornada) se descuenta de la duración del ciclo.

CREATE TABLE mod03_interrupcion_corte (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    programacion_id bigint NOT NULL REFERENCES mod03_programacion_servicio (id) ON DELETE CASCADE,
    zona_afectada varchar(120) NOT NULL,
    zona_alternativa varchar(120),
    hora timestamptz NOT NULL,
    motivo varchar(300) NOT NULL CHECK (length(trim(motivo)) > 0),
    minutos_descontados integer NOT NULL CHECK (minutos_descontados >= 0),
    aviso_proveedor boolean NOT NULL DEFAULT false,
    registrada_como_restriccion boolean NOT NULL DEFAULT false,
    usuario_id bigint NOT NULL REFERENCES core_usuario (id),
    fecha_registro timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX mod03_interrupcion_corte_ciclo ON mod03_interrupcion_corte (programacion_id, hora);
