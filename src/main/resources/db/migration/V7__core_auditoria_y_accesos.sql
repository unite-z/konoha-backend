-- AV-222 (RF-T-008) y AV-216 (RF-T-001): auditoría común de altas y cambios, y registro de accesos.
-- Las dos tablas solo admiten inserciones (RI-35, RNF-009): un trigger rechaza UPDATE y DELETE.

CREATE TABLE core_registro_auditoria (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    entidad varchar(60) NOT NULL,
    registro_id bigint NOT NULL,
    accion varchar(30) NOT NULL
        CHECK (accion IN ('Alta', 'Modificacion', 'CambioEstado', 'CambioRol', 'BajaLogica')),
    usuario_id bigint NOT NULL REFERENCES core_usuario (id),
    fecha_hora timestamptz NOT NULL DEFAULT now(),
    valores_anteriores jsonb NOT NULL DEFAULT '{}'::jsonb,
    valores_nuevos jsonb NOT NULL DEFAULT '{}'::jsonb,
    motivo text
);

CREATE INDEX core_registro_auditoria_registro ON core_registro_auditoria (entidad, registro_id, fecha_hora);

CREATE TABLE core_registro_acceso (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id bigint REFERENCES core_usuario (id),
    -- Lo que escribió la persona cuando no corresponde a ninguna cuenta. Nunca la contraseña.
    identificador varchar(150),
    fecha_hora timestamptz NOT NULL DEFAULT now(),
    canal varchar(20) NOT NULL CHECK (canal IN ('oficina', 'campo', 'api')),
    resultado varchar(30) NOT NULL
        CHECK (resultado IN ('Exitoso', 'Fallido', 'Bloqueado', 'Denegado', 'SinPermiso', 'CierreSesion')),
    motivo varchar(200),
    ruta varchar(300)
);

CREATE INDEX core_registro_acceso_usuario ON core_registro_acceso (usuario_id, fecha_hora);

CREATE FUNCTION core_rechazar_cambio_historial() RETURNS trigger AS $$
BEGIN
    RAISE EXCEPTION 'El historial de MOD-01 solo permite inserciones';
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER core_auditoria_inmutable BEFORE UPDATE OR DELETE ON core_registro_auditoria
FOR EACH ROW EXECUTE FUNCTION core_rechazar_cambio_historial();

CREATE TRIGGER core_accesos_inmutables BEFORE UPDATE OR DELETE ON core_registro_acceso
FOR EACH ROW EXECUTE FUNCTION core_rechazar_cambio_historial();
