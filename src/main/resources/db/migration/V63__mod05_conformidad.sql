-- RF-SER-007: conformidad u observación del informe del proveedor. Una fila por decisión del jefe de sección,
-- ligada a la revisión del informe que evaluó; una revisión solo admite una decisión. Una observación deja la
-- atención «Observado» hasta que el proveedor suba otra revisión (RF-SER-012), que admitirá su propia decisión.
-- Como el historial de estados, solo permite inserciones: la decisión es constancia.
CREATE TABLE mod05_conformidad (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    atencion_id bigint NOT NULL REFERENCES mod05_atenciontercerizada(id),
    reporte_id bigint NOT NULL UNIQUE REFERENCES mod05_reporteproveedor(id),
    resultado varchar(10) NOT NULL CHECK (resultado IN ('Conforme', 'Observada')),
    fecha_conformidad date NOT NULL,
    comentarios text NOT NULL DEFAULT '',
    usuario_id bigint NOT NULL REFERENCES mod05_usuario(id),
    fecha_creacion timestamp with time zone NOT NULL DEFAULT now(),
    CONSTRAINT mod05_conformidad_observada_comenta CHECK (resultado = 'Conforme' OR btrim(comentarios) <> '')
);
CREATE INDEX mod05_conformidad_atencion ON mod05_conformidad(atencion_id);
CREATE TRIGGER mod05_conformidad_inmutable BEFORE UPDATE OR DELETE ON mod05_conformidad
FOR EACH ROW EXECUTE FUNCTION mod05_rechazar_cambio_historial();
