-- AV-278 (RF-INC-004): una incidencia derivada a un proveedor queda enlazada a su atención de MOD-05.
-- Una fila por derivación: si se deriva de nuevo, manda la última. Solo añade (expand).
CREATE TABLE mod03_requerimiento_incidencia (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    incidencia_id bigint NOT NULL REFERENCES mod03_incidencia (id),
    atencion_id bigint NOT NULL UNIQUE REFERENCES mod05_atenciontercerizada (id),
    proveedor_id bigint NOT NULL REFERENCES mod05_proveedor (id),
    tipo_atencion varchar(15) NOT NULL CHECK (tipo_atencion IN ('Programada', 'Extraordinaria')),
    usuario_id bigint NOT NULL REFERENCES core_usuario (id),
    fecha_hora timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX mod03_requerimiento_incidencia_incidencia
    ON mod03_requerimiento_incidencia (incidencia_id, fecha_hora DESC);
