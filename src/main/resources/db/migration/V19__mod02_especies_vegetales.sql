-- AV-140: catálogo de especies que pueden asociarse a ejemplares.
CREATE TABLE mod02_especie_vegetal (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_comun varchar(150),
    nombre_cientifico varchar(200),
    forma_biologica varchar(80) NOT NULL,
    activo boolean NOT NULL DEFAULT true,
    fecha_creacion timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT mod02_especie_con_nombre CHECK (
        nullif(trim(nombre_comun), '') IS NOT NULL
        OR nullif(trim(nombre_cientifico), '') IS NOT NULL
    )
);

CREATE UNIQUE INDEX mod02_especie_cientifico_unico
    ON mod02_especie_vegetal (lower(nombre_cientifico))
    WHERE nombre_cientifico IS NOT NULL AND length(trim(nombre_cientifico)) > 0;
CREATE UNIQUE INDEX mod02_especie_comun_sin_cientifico_unico
    ON mod02_especie_vegetal (lower(nombre_comun))
    WHERE nombre_cientifico IS NULL AND nombre_comun IS NOT NULL;
