-- RF-FIT-003: catálogo de productos agronómicos usados en control fitosanitario.
CREATE TABLE mod05_producto_agronomico (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 nombre varchar(150) NOT NULL UNIQUE,
 principio_activo varchar(150) NOT NULL DEFAULT '',
 presentacion varchar(120) NOT NULL DEFAULT '',
 activo boolean NOT NULL DEFAULT true
);

-- Productos aplicados en una atención. Un producto desactivado conserva sus referencias históricas:
-- esta tabla solo referencia el id, nunca copia sus datos.
CREATE TABLE mod05_atencion_producto (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 atencion_id bigint NOT NULL REFERENCES mod05_atenciontercerizada(id),
 producto_id bigint NOT NULL REFERENCES mod05_producto_agronomico(id),
 dosis varchar(120) NOT NULL DEFAULT '',
 CONSTRAINT mod05_atencion_producto_unico UNIQUE (atencion_id, producto_id)
);
CREATE INDEX mod05_atencion_producto_atencion ON mod05_atencion_producto (atencion_id);
CREATE INDEX mod05_atencion_producto_producto ON mod05_atencion_producto (producto_id);
