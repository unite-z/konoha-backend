-- MOD-04: AV-220 (RF-T-005), AV-191 (RF-PLA-005) y AV-66 (RF-ACT-003).
-- MOD-04 utiliza las cuentas y la sesión común de MOD-01.
ALTER TABLE mod05_usuario_rol DROP CONSTRAINT mod05_usuario_rol_rol_check;
ALTER TABLE mod05_usuario_rol ADD CONSTRAINT mod05_usuario_rol_rol_check
 CHECK (rol IN ('Jefe de sección','Ingeniero de campo','Practicante autorizado','Capataz'));

CREATE TABLE mod04_personal (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 nombres varchar(100) NOT NULL CHECK (length(trim(nombres)) > 0),
 apellidos varchar(150) NOT NULL CHECK (length(trim(apellidos)) > 0),
 tipo_personal varchar(20) NOT NULL CHECK (tipo_personal IN ('Capataz','Operario')),
 activo boolean NOT NULL DEFAULT true,
 usuario_id bigint UNIQUE REFERENCES core_usuario(id),
 CHECK (tipo_personal = 'Capataz' OR usuario_id IS NULL)
);
CREATE TABLE mod04_cuadrilla (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 nombre varchar(150) NOT NULL CHECK (length(trim(nombre)) > 0),
 capataz_id bigint NOT NULL REFERENCES mod04_personal(id),
 activa boolean NOT NULL DEFAULT true,
 fecha_creacion timestamptz NOT NULL DEFAULT now(),
 usuario_creacion_id bigint NOT NULL REFERENCES core_usuario(id),
 fecha_modificacion timestamptz NOT NULL DEFAULT now(),
 usuario_modificacion_id bigint NOT NULL REFERENCES core_usuario(id)
);
CREATE UNIQUE INDEX mod04_cuadrilla_nombre ON mod04_cuadrilla(lower(trim(nombre)));
CREATE UNIQUE INDEX mod04_capataz_cuadrilla_activa ON mod04_cuadrilla(capataz_id) WHERE activa;
CREATE TABLE mod04_asignacion_cuadrilla (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 cuadrilla_id bigint NOT NULL REFERENCES mod04_cuadrilla(id),
 operario_id bigint NOT NULL REFERENCES mod04_personal(id),
 fecha_inicio date NOT NULL,
 -- Fin exclusivo: [inicio, fin). Un movimiento el mismo día puede dejar un intervalo vacío.
 fecha_fin date CHECK (fecha_fin >= fecha_inicio)
);
CREATE UNIQUE INDEX mod04_operario_asignacion_actual ON mod04_asignacion_cuadrilla(operario_id) WHERE fecha_fin IS NULL;
CREATE INDEX mod04_asignacion_cuadrilla_equipo_idx ON mod04_asignacion_cuadrilla(cuadrilla_id);
-- Proyecciones locales de los catálogos del dominio. No modifican las tablas de MOD-05.
CREATE TABLE mod04_tipo_actividad (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 nombre varchar(150) NOT NULL, activo boolean NOT NULL DEFAULT true
);
CREATE TABLE mod04_encargo (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 cuadrilla_id bigint NOT NULL REFERENCES mod04_cuadrilla(id),
 capataz_id bigint NOT NULL REFERENCES mod04_personal(id),
 tipo_actividad_id bigint NOT NULL REFERENCES mod04_tipo_actividad(id),
 area_verde_id bigint NOT NULL REFERENCES mod05_areaverde(id),
 descripcion varchar(1000) NOT NULL CHECK (length(trim(descripcion)) > 0),
 periodicidad varchar(10) NOT NULL CHECK (periodicidad IN ('Semanal','Quincenal')),
 fecha_reunion date NOT NULL,
 fecha_inicio date NOT NULL, fecha_fin date NOT NULL,
 plazo_previsto date NOT NULL,
 fecha_creacion timestamptz NOT NULL DEFAULT now(),
 usuario_creacion_id bigint NOT NULL REFERENCES core_usuario(id),
 fecha_modificacion timestamptz NOT NULL DEFAULT now(),
 usuario_modificacion_id bigint NOT NULL REFERENCES core_usuario(id),
 CHECK (fecha_fin >= fecha_inicio),
 CHECK (fecha_fin - fecha_inicio < CASE WHEN periodicidad='Semanal' THEN 7 ELSE 14 END),
 CHECK (plazo_previsto BETWEEN fecha_inicio AND fecha_fin)
);
CREATE INDEX mod04_encargo_periodo ON mod04_encargo(capataz_id,fecha_inicio,fecha_fin);
CREATE TABLE mod04_parte_diario (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 cuadrilla_id bigint NOT NULL REFERENCES mod04_cuadrilla(id),
 capataz_id bigint NOT NULL REFERENCES mod04_personal(id),
 fecha date NOT NULL,
 estado varchar(10) NOT NULL DEFAULT 'Abierto' CHECK (estado IN ('Abierto','Cerrado')),
 usuario_creacion_id bigint NOT NULL REFERENCES core_usuario(id),
 UNIQUE(cuadrilla_id,fecha)
);
CREATE TABLE mod04_actividad (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 parte_id bigint NOT NULL REFERENCES mod04_parte_diario(id),
 tipo_actividad_id bigint NOT NULL REFERENCES mod04_tipo_actividad(id),
 area_verde_id bigint NOT NULL REFERENCES mod05_areaverde(id),
 fecha_hora_actividad timestamptz NOT NULL,
 encargo_id bigint REFERENCES mod04_encargo(id),
 observaciones varchar(1000),
 usuario_creacion_id bigint NOT NULL REFERENCES core_usuario(id)
);
CREATE TABLE mod04_participacion_actividad (
 actividad_id bigint NOT NULL REFERENCES mod04_actividad(id),
 operario_id bigint NOT NULL REFERENCES mod04_personal(id),
 PRIMARY KEY(actividad_id,operario_id)
);
-- La auditoría pertenece a MOD-01: las operaciones usan RegistradorAuditoria y core_registro_auditoria.

-- Claves por usuario; la limpieza se realiza al reutilizar una clave caducada.
CREATE TABLE mod04_idempotencia (
 usuario_id bigint NOT NULL REFERENCES core_usuario(id),
 clave uuid NOT NULL,
 hash varchar(64) NOT NULL,
 respuesta jsonb NOT NULL,
 caduca timestamptz NOT NULL DEFAULT now() + interval '24 hours',
 PRIMARY KEY (usuario_id,clave)
);
