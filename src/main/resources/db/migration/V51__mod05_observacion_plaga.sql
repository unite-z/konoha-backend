-- RF-FIT-005: observaciones de presencia de plagas en un espacio o ejemplar que justifican una
-- aplicación o su intensidad. Es un registro de campo, no editable: una corrección se registra como
-- una observación nueva, nunca sobrescribiendo la anterior (no sustituye la evaluación técnica).
CREATE TABLE mod05_observacion_plaga (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 area_verde_id bigint NULL REFERENCES mod05_areaverde(id),
 -- mod05_ejemplar es una vista de solo lectura (AV-287): la referencia va a la tabla real de MOD-02.
 ejemplar_id bigint NULL REFERENCES mod02_ejemplar(id),
 plaga_id bigint NOT NULL REFERENCES mod05_plaga(id),
 descripcion text NOT NULL,
 fecha_observacion date NOT NULL,
 fecha_creacion timestamp with time zone NOT NULL,
 usuario_creacion_id bigint NOT NULL REFERENCES mod05_usuario(id),
 CONSTRAINT mod05_observacion_destino CHECK (
  (area_verde_id IS NOT NULL AND ejemplar_id IS NULL) OR (area_verde_id IS NULL AND ejemplar_id IS NOT NULL)
 )
);
CREATE INDEX mod05_observacion_plaga_area ON mod05_observacion_plaga (area_verde_id);
CREATE INDEX mod05_observacion_plaga_ejemplar ON mod05_observacion_plaga (ejemplar_id);
CREATE INDEX mod05_observacion_plaga_plaga ON mod05_observacion_plaga (plaga_id);
