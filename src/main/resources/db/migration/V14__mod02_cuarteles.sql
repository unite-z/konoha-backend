-- AV-104 / RF-INV-001: cuarteles como referencia histórica opcional.
CREATE TABLE mod02_cuartel (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    numero varchar(40) NOT NULL UNIQUE,
    nombre varchar(120) NOT NULL,
    estado varchar(20) NOT NULL DEFAULT 'vigente'
        CHECK (estado IN ('vigente', 'desaparecido')),
    fecha_creacion timestamptz NOT NULL DEFAULT now(),
    usuario_creacion_id bigint REFERENCES core_usuario(id),
    fecha_modificacion timestamptz NOT NULL DEFAULT now(),
    usuario_modificacion_id bigint REFERENCES core_usuario(id),
    CONSTRAINT mod02_cuartel_nombre_no_vacio CHECK (length(trim(nombre)) > 0)
);
