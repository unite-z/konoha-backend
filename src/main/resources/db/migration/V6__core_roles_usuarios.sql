    ('ingeniero-campo', 'Ingeniero de campo', 'Coordina y supervisa el trabajo técnico', true),
    ('practicante', 'Practicante', 'Apoya y actualiza registros, normalmente con fin de vigencia', true),
    ('capataz', 'Capataz', 'Responsable de una cuadrilla. Registra desde el móvil asignado', true),
    ('operario', 'Operario', 'Previsto para una fase posterior. Se registra como persona de una cuadrilla', false)
ON CONFLICT (codigo) DO NOTHING;

CREATE TABLE core_usuario (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_usuario varchar(150) NOT NULL UNIQUE,
    -- Nulo solo en las cuentas copiadas de MOD-05, que no tenían correo. El alta nueva lo exige.
    correo varchar(120),
    nombre varchar(200) NOT NULL,
    telefono varchar(30),
    credencial_hash varchar(255) NOT NULL,
    rol_id bigint NOT NULL REFERENCES core_rol (id),
    personal_id bigint,
    activo boolean NOT NULL DEFAULT true,
    fecha_fin_vigencia date,
    debe_cambiar_contrasena boolean NOT NULL DEFAULT false,
    intentos_fallidos integer NOT NULL DEFAULT 0 CHECK (intentos_fallidos >= 0),
    bloqueado_hasta timestamptz,
    ultimo_acceso timestamptz,
    fecha_creacion timestamptz NOT NULL DEFAULT now(),
    usuario_creacion_id bigint REFERENCES core_usuario (id),
    fecha_modificacion timestamptz NOT NULL DEFAULT now(),
    usuario_modificacion_id bigint REFERENCES core_usuario (id),
    CONSTRAINT core_usuario_correo_formato CHECK (correo IS NULL OR correo ~ '^[^@\s]+@[^@\s]+$')
);

CREATE UNIQUE INDEX core_usuario_correo_unico ON core_usuario (lower(correo)) WHERE correo IS NOT NULL;
CREATE INDEX core_usuario_rol ON core_usuario (rol_id);

CREATE FUNCTION core_exigir_rol_activo() RETURNS trigger AS $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM core_rol WHERE id = NEW.rol_id AND activo) THEN
        RAISE EXCEPTION 'El rol % no está habilitado en esta fase', NEW.rol_id
            USING ERRCODE = 'check_violation';
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER core_rol_debe_estar_activo BEFORE INSERT OR UPDATE OF rol_id ON core_usuario
FOR EACH ROW EXECUTE FUNCTION core_exigir_rol_activo();

-- Copia de las cuentas de MOD-05. Cada una se queda con un único rol (el de más alcance). Las que no
-- tenían rol entran inactivas como practicante: no pueden entrar hasta que el jefe las revise.
INSERT INTO core_usuario (id, nombre_usuario, correo, nombre, credencial_hash, rol_id, activo)
SELECT u.id,
       u.usuario,
       CASE WHEN u.usuario ~ '^[^@\s]+@[^@\s]+$' THEN lower(u.usuario) END,
       u.nombre,
       u.password_hash,
       (SELECT r.id FROM core_rol r WHERE r.codigo = coalesce(m.codigo, 'practicante')),
       u.activo AND m.codigo IS NOT NULL
FROM mod05_usuario u
LEFT JOIN LATERAL (
    SELECT CASE ur.rol
               WHEN 'Jefe de sección' THEN 'jefe-seccion'
               WHEN 'Ingeniero de campo' THEN 'ingeniero-campo'
               WHEN 'Capataz' THEN 'capataz'
               ELSE 'practicante'
           END AS codigo
    FROM mod05_usuario_rol ur
    WHERE ur.usuario_id = u.id
    ORDER BY CASE ur.rol
                 WHEN 'Jefe de sección' THEN 1
                 WHEN 'Ingeniero de campo' THEN 2
                 WHEN 'Practicante autorizado' THEN 3
                 ELSE 4
             END
    LIMIT 1
) m ON true
ON CONFLICT (id) DO NOTHING;

SELECT setval(pg_get_serial_sequence('core_usuario', 'id'), coalesce((SELECT max(id) FROM core_usuario), 0) + 1, false);
