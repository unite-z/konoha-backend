-- AV-218 (RF-T-003), AV-216 (RF-T-001) y AV-217 (RF-T-002): roles y usuarios de MOD-01.
-- Un usuario tiene exactamente un rol (rol_id NOT NULL). El operario queda previsto e inactivo (RS-004):
-- un trigger impide asignar un rol inactivo, también desde futuros módulos.
-- Las cuentas provisionales de mod05_usuario se copian con el mismo id para que la consolidación
-- posterior (expand/contract, ticket propio) no tenga que traducir claves foráneas.

CREATE TABLE core_rol (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo varchar(40) NOT NULL UNIQUE,
    nombre varchar(60) NOT NULL UNIQUE,
    descripcion varchar(300) NOT NULL,
    activo boolean NOT NULL
);

