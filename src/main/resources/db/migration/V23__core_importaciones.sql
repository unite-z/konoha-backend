-- AV-223 / RF-T-009: importación repetible desde Excel. Cada carga se valida antes de tocar datos
-- oficiales y su resultado queda registrado. Las filas guardan los valores tal como llegaron.
CREATE TABLE core_importacion (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo varchar(30) NOT NULL,
    nombre_archivo varchar(255) NOT NULL,
    estado varchar(20) NOT NULL DEFAULT 'Validada' CHECK (estado IN ('Validada', 'Confirmada')),
    total integer NOT NULL,
    altas integer NOT NULL,
    actualizaciones integer NOT NULL,
    sin_cambios integer NOT NULL,
    revisar integer NOT NULL,
    errores integer NOT NULL,
    usuario_id bigint NOT NULL REFERENCES core_usuario(id),
    fecha_creacion timestamptz NOT NULL DEFAULT now(),
    fecha_confirmacion timestamptz
);

CREATE TABLE core_importacion_fila (
    importacion_id bigint NOT NULL REFERENCES core_importacion(id) ON DELETE CASCADE,
    fila integer NOT NULL,
    codigo varchar(150),
    resultado varchar(20) NOT NULL
        CHECK (resultado IN ('Alta', 'Actualización', 'Sin cambios', 'Revisar', 'Error')),
    detalle varchar(500) NOT NULL DEFAULT '',
    datos jsonb NOT NULL,
    PRIMARY KEY (importacion_id, fila)
);
