CREATE TABLE core_permiso (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo varchar(60) NOT NULL UNIQUE CHECK (codigo ~ '^[A-Z0-9_]+\.[A-Z0-9_]+\.[A-Z0-9_]+$'),
    modulo varchar(6) NOT NULL CHECK (modulo IN ('MOD-01', 'MOD-02', 'MOD-03', 'MOD-04', 'MOD-05', 'MOD-06')),
    descripcion varchar(200) NOT NULL,
    es_sensible boolean NOT NULL DEFAULT false
);

CREATE TABLE core_rol_permiso (
    rol_id bigint NOT NULL REFERENCES core_rol (id),
    permiso_id bigint NOT NULL REFERENCES core_permiso (id),
    PRIMARY KEY (rol_id, permiso_id)
);

