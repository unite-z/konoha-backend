-- AV-13 · MOD-03: calendario de restricciones (HU-MOD03-003, RF-PLA-003, RN-003).
-- Modelo de BD v1, secciones 4.3.4 (TipoRestriccion) y 4.3.5 (RestriccionCalendario). Añade `serie`
-- (restricciones generadas juntas por una recurrencia) y `activo` (baja lógica); reserva_id llegará
-- con la carga de reservas (RF-PLA-010).
CREATE TABLE mod03_tipo_restriccion (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre varchar(80) NOT NULL UNIQUE,
    efecto varchar(12) NOT NULL CHECK (efecto IN ('Prohibicion', 'Advertencia', 'Favorable')),
    aplica_servicios_ruidosos boolean NOT NULL,
    activo boolean NOT NULL DEFAULT true
);

-- Catálogo de referencia (tipos que enumera RF-PLA-003). Idempotente.
INSERT INTO mod03_tipo_restriccion (nombre, efecto, aplica_servicios_ruidosos) VALUES
    ('Feriado', 'Prohibicion', false),
    ('Cierre del campus', 'Prohibicion', false),
    ('Paro', 'Prohibicion', false),
    ('Evento masivo', 'Prohibicion', true),
    ('Examen de admisión', 'Prohibicion', true),
    ('Evaluación semestral', 'Prohibicion', true),
    ('Evaluación de fin de ciclo', 'Prohibicion', true),
    ('Actividad extracurricular', 'Advertencia', true),
    ('Reserva de jardín', 'Advertencia', false),
    ('Día sin actividad académica', 'Favorable', true)
ON CONFLICT (nombre) DO NOTHING;

CREATE TABLE mod03_restriccion_calendario (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo_restriccion_id bigint NOT NULL REFERENCES mod03_tipo_restriccion (id),
    fecha_inicio date NOT NULL,
    fecha_fin date NOT NULL,
    hora_inicio time,
    hora_fin time,
    area_verde_id bigint REFERENCES mod05_areaverde (id),
    descripcion varchar(200),
    serie uuid,
    activo boolean NOT NULL DEFAULT true,
    fecha_creacion timestamptz NOT NULL DEFAULT now(),
    usuario_creacion_id bigint NOT NULL REFERENCES mod05_usuario (id),
    fecha_modificacion timestamptz NOT NULL DEFAULT now(),
    usuario_modificacion_id bigint NOT NULL REFERENCES mod05_usuario (id),
    CONSTRAINT mod03_restriccion_fechas CHECK (fecha_fin >= fecha_inicio),
    CONSTRAINT mod03_restriccion_horas CHECK (hora_inicio IS NULL OR hora_fin IS NULL OR hora_fin > hora_inicio)
);

CREATE INDEX mod03_restriccion_periodo ON mod03_restriccion_calendario (fecha_inicio, fecha_fin) WHERE activo;
CREATE INDEX mod03_restriccion_serie ON mod03_restriccion_calendario (serie) WHERE serie IS NOT NULL;
