-- AV-253 (RF-PLA-004 v6, CU-004): motivo de la cancelación e historial de transiciones de cada
-- programación (Programada, EnCurso, Completada, Cancelada) con autor y hora. Solo añade (expand).

ALTER TABLE mod03_programacion_servicio ADD COLUMN motivo_cancelacion varchar(300);

CREATE TABLE mod03_historial_programacion (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    programacion_id bigint NOT NULL REFERENCES mod03_programacion_servicio (id),
    estado varchar(12) NOT NULL CHECK (estado IN ('Programada', 'EnCurso', 'Completada', 'Cancelada')),
    fecha_hora timestamptz NOT NULL DEFAULT now(),
    usuario_id bigint NOT NULL REFERENCES mod05_usuario (id),
    motivo varchar(300)
);

CREATE INDEX mod03_historial_programacion_ciclo ON mod03_historial_programacion (programacion_id, fecha_hora);

-- Las programaciones que ya existen: su alta y, si ya cambió, su estado actual con la última modificación.
INSERT INTO mod03_historial_programacion (programacion_id, estado, fecha_hora, usuario_id)
SELECT id, 'Programada', fecha_creacion, creado_por_id FROM mod03_programacion_servicio;

INSERT INTO mod03_historial_programacion (programacion_id, estado, fecha_hora, usuario_id)
SELECT id, estado, fecha_modificacion, usuario_modificacion_id FROM mod03_programacion_servicio
WHERE estado <> 'Programada';
