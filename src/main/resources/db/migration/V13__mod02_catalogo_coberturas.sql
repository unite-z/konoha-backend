-- AV-115 / RF-INV-003: catálogo configurable de coberturas vegetales.
CREATE TABLE mod02_cobertura_vegetal (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre varchar(120) NOT NULL,
    activo boolean NOT NULL DEFAULT true,
    fecha_creacion timestamptz NOT NULL DEFAULT now(),
    usuario_creacion_id bigint REFERENCES core_usuario(id),
    fecha_modificacion timestamptz NOT NULL DEFAULT now(),
    usuario_modificacion_id bigint REFERENCES core_usuario(id),
    CONSTRAINT mod02_cobertura_vegetal_nombre_no_vacio CHECK (length(trim(nombre)) > 0)
);
CREATE UNIQUE INDEX mod02_cobertura_vegetal_nombre_unico
    ON mod02_cobertura_vegetal (lower(nombre));

INSERT INTO mod02_cobertura_vegetal (nombre)
SELECT valores.nombre
FROM (VALUES
    ('Grass americano'),
    ('Grass bermuda'),
    ('Paspalum'),
    ('Vegetación herbácea'),
    ('Setos'),
    ('Cobertura xerofítica')
) AS valores(nombre)
WHERE NOT EXISTS (
    SELECT 1 FROM mod02_cobertura_vegetal c WHERE lower(c.nombre) = lower(valores.nombre)
);
