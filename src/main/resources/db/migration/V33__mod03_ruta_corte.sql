-- AV-259 (RF-COR-001, HU-010 y CU-010): al programar un corte se copia la ruta de jardines de MOD-02
-- (las áreas verdes de las zonas elegidas; la zona es su sector vigente) en ese momento, para que
-- un cambio posterior en MOD-02 no altere el ciclo. AV-260 a AV-262 marcan, interrumpen y limpian
-- sobre esta copia.

CREATE TABLE mod03_ruta_corte (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    programacion_id bigint NOT NULL REFERENCES mod03_programacion_servicio (id) ON DELETE CASCADE,
    area_verde_id bigint NOT NULL REFERENCES mod02_area_verde (id),
    zona varchar(120) NOT NULL,
    orden integer NOT NULL,
    estado varchar(10) NOT NULL DEFAULT 'Pendiente' CHECK (estado IN ('Pendiente', 'Cortado')),
    marcado_en timestamptz,
    marcado_por_id bigint REFERENCES core_usuario (id),
    CONSTRAINT mod03_ruta_corte_jardin UNIQUE (programacion_id, area_verde_id)
);

CREATE INDEX mod03_ruta_corte_ciclo ON mod03_ruta_corte (programacion_id, orden);
