-- AV-445: historial de los cambios de contorno de un área verde (quién, cuándo y superficie).
CREATE TABLE mod02_historial_contorno_area (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    area_verde_id bigint NOT NULL REFERENCES mod02_area_verde(id) ON DELETE RESTRICT,
    id_fuente uuid NOT NULL,
    fecha timestamptz NOT NULL DEFAULT now(),
    usuario_id bigint NOT NULL REFERENCES core_usuario(id),
    superficie_anterior_m2 numeric(12, 2),
    superficie_nueva_m2 numeric(12, 2) NOT NULL CHECK (superficie_nueva_m2 > 0),
    ejemplares_desvinculados integer NOT NULL DEFAULT 0 CHECK (ejemplares_desvinculados >= 0)
);
CREATE INDEX mod02_historial_contorno_area_busqueda
    ON mod02_historial_contorno_area (area_verde_id, fecha DESC, id DESC);
